"""Market maker forward quotes for futures contracts (M18.3).

The Merchants Guild quotes forward prices for 10, 20, and 30 days:
``forward = int(round(spot * (1.0 + carry * days) * risk_factor))``

- ``carry``: daily storage & cost of carry rate (default 0.002 / day).
- ``risk_factor``: derived from stock cover (stock_days / normal_cover). Low cover increases
  scarcity premium; abundant cover approaches 1.0.
- ``exposure_cap``: Merchants Guild open exposure is capped by its treasury.
- Each quote stores its inputs (spot, cover, carry) as verifiable provenance evidence.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import TYPE_CHECKING, Any

if TYPE_CHECKING:
    from questless.sim.ledger import Ledger


@dataclass(frozen=True)
class ForwardQuote:
    """A forward price quote generated by the market maker."""

    good: str
    days: int
    spot: int
    forward: int
    stock_cover: float  # days of stock on hand
    carry_rate: float
    risk_factor: float
    max_qty: int  # maximum contracts market maker will write given exposure cap
    tick: int = 0
    evidence: dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> dict[str, Any]:
        return {
            "good": self.good,
            "days": self.days,
            "spot": self.spot,
            "forward": self.forward,
            "stock_cover": self.stock_cover,
            "carry_rate": self.carry_rate,
            "risk_factor": self.risk_factor,
            "max_qty": self.max_qty,
            "tick": self.tick,
            "evidence": dict(self.evidence),
        }

    @classmethod
    def from_dict(cls, data: dict[str, Any]) -> ForwardQuote:
        return cls(
            good=data["good"],
            days=data["days"],
            spot=data["spot"],
            forward=data["forward"],
            stock_cover=data["stock_cover"],
            carry_rate=data["carry_rate"],
            risk_factor=data["risk_factor"],
            max_qty=data["max_qty"],
            tick=data.get("tick", 0),
            evidence=data.get("evidence", {}),
        )


class MarketMaker:
    """Merchants Guild market maker for forward quotes and futures contracts."""

    DEFAULT_HORIZONS = (10, 20, 30)

    def __init__(
        self,
        guild_id: str = "merchants",
        base_carry: float = 0.002,
        normal_cover_days: float = 14.0,
        max_exposure_share: float = 0.50,
    ) -> None:
        self.guild_id = guild_id
        self.base_carry = base_carry
        self.normal_cover_days = normal_cover_days
        self.max_exposure_share = max_exposure_share
        self.active_exposure: int = 0

    def calculate_risk_factor(self, stock_cover: float) -> float:
        """Calculate risk factor from stock cover ratio."""
        if stock_cover <= 0.0:
            return 1.40
        ratio = stock_cover / self.normal_cover_days
        if ratio >= 1.0:
            return 1.0
        # Linear risk premium up to +35% as stock cover depletes
        return round(1.0 + 0.35 * (1.0 - ratio), 3)

    def quote(
        self,
        good: str,
        spot: int,
        days: int,
        stock_cover: float,
        treasury_balance: int,
        tick: int = 0,
    ) -> ForwardQuote:
        """Compute a deterministic forward quote for a given good and horizon."""
        if spot <= 0:
            raise ValueError(f"Spot price must be positive, got {spot}")
        if days <= 0:
            raise ValueError(f"Days must be positive, got {days}")

        risk = self.calculate_risk_factor(stock_cover)
        carry_multiplier = 1.0 + (self.base_carry * days)
        forward_price = max(1, int(round(spot * carry_multiplier * risk)))

        # Exposure limit: Merchants Guild caps total exposure to max_exposure_share of treasury
        allowed_exposure = int(treasury_balance * self.max_exposure_share)
        remaining_exposure = max(0, allowed_exposure - self.active_exposure)
        max_contracts = remaining_exposure // max(1, forward_price)

        evidence = {
            "spot": spot,
            "days": days,
            "stock_cover": stock_cover,
            "carry_rate": self.base_carry,
            "risk_factor": risk,
            "treasury": treasury_balance,
            "allowed_exposure": allowed_exposure,
            "remaining_exposure": remaining_exposure,
        }

        return ForwardQuote(
            good=good,
            days=days,
            spot=spot,
            forward=forward_price,
            stock_cover=stock_cover,
            carry_rate=self.base_carry,
            risk_factor=risk,
            max_qty=max_contracts,
            tick=tick,
            evidence=evidence,
        )

    def quote_board(
        self,
        goods_spot: dict[str, int],
        goods_cover: dict[str, float],
        ledger: Ledger,
        guild_account: str,
        tick: int = 0,
        horizons: tuple[int, ...] = DEFAULT_HORIZONS,
    ) -> dict[str, dict[int, ForwardQuote]]:
        """Generate a complete quote board for all goods across standard horizons."""
        treasury = ledger.balance(guild_account, "coin")
        board: dict[str, dict[int, ForwardQuote]] = {}

        for good, spot in sorted(goods_spot.items()):
            cover = goods_cover.get(good, self.normal_cover_days)
            board[good] = {}
            for days in horizons:
                q = self.quote(
                    good=good,
                    spot=spot,
                    days=days,
                    stock_cover=cover,
                    treasury_balance=treasury,
                    tick=tick,
                )
                board[good][days] = q

        return board
