"""Experiment (M58.2): does a world that has run for years still reward a newcomer?

    uv run python experiments/late_joiners.py                     # 5 seeds, join on day 1,000
    uv run python experiments/late_joiners.py --seeds 10 --join 2000

For each scenario and seed, the same scripted player (``ScriptedPlayer`` from
``shock_vs_baseline.py``, local strategy) plays ``WINDOW`` days in two worlds:

    day 0       joins a fresh world; the scenario's shock hits as usual
    day <join>  joins a world that has already run ``join`` days; the same shock is moved so it
                hits the same number of days after the player arrives

Both are compared at equal days played, so any gap comes from the world's age: prices, guild
treasuries, the town's budget and who already holds the coin. There is only one player in the
engine until M31, so incumbent players' head start (reputation, capital, land) isn't modelled
yet; this measures what the world itself offers a newcomer.

Outputs in experiments/results/: late_joiners.csv (one row per run) and late_joiners.md.
"""

from __future__ import annotations

import argparse
import csv
import dataclasses
import statistics as st
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments"))

from shock_vs_baseline import ScriptedPlayer  # noqa: E402

from questless.api import Simulation  # noqa: E402
from questless.config import load_scenario  # noqa: E402
from questless.contracts.model import Status  # noqa: E402
from questless.sim.entities import PLAYER  # noqa: E402
from questless.sim.ledger import Asset  # noqa: E402

RESULTS = ROOT / "experiments" / "results"
WINDOW = 120
SCENARIOS = ("iron_shortage", "mine_disaster", "drought")
METRICS = (
    "profit",
    "contracts_fulfilled",
    "days_to_first_contract",
    "reputation",
    "contracts_posted",
    "town_treasury",
)


def run(scenario: str, seed: int, join: int, window: int = WINDOW) -> dict:
    """One player joining on day ``join`` and playing ``window`` days; the shock is shifted by
    ``join`` so it lands at the same point in the player's time."""
    cfg = load_scenario(ROOT / "scenarios" / f"{scenario}.toml")
    shocks = tuple(dataclasses.replace(s, start=s.start + join) for s in cfg.shocks)
    sim = Simulation.from_scenario(dataclasses.replace(cfg, seed=seed, shocks=shocks))
    sim.step(join)
    bot = ScriptedPlayer(sim, "local")
    coin_at_join = sim.player()["coin"]
    first = None
    for day in range(window):
        bot.act()
        sim.step()
        if first is None and any(
            c.status is Status.FULFILLED and c.accepted_by == PLAYER for c in sim.contracts()
        ):
            first = day + 1
    in_window = [c for c in sim.contracts() if c.created_tick >= join]
    return {
        "scenario": scenario,
        "seed": seed,
        "join": join,
        "profit": sim.player()["coin"] - coin_at_join,
        "contracts_fulfilled": sum(
            c.status is Status.FULFILLED and c.accepted_by == PLAYER for c in in_window
        ),
        "days_to_first_contract": first,
        "reputation": sum(sim.player()["reputation"].values()),
        "contracts_posted": len(in_window),
        "town_treasury": sim.world.ledger.balance("town", Asset.COIN),
    }


def summarise(rows: list[dict], joins: tuple[int, int]) -> str:
    def cell(values: list) -> str:
        values = [v for v in values if v is not None]
        if not values:
            return "n/a"
        return f"{st.median(values):.0f} ({min(values):.0f} to {max(values):.0f})"

    seeds = len({r["seed"] for r in rows})
    lines = [
        "# Late joiners (M58.2)\n",
        f"Median (range) over {seeds} seeds, {WINDOW} days played, same shock timing relative to "
        "joining. Generated by `experiments/late_joiners.py`.\n",
    ]
    for scenario in SCENARIOS:
        lines += [
            f"\n## {scenario.replace('_', ' ').title()}\n",
            "| Metric | " + " | ".join(f"Joins day {j}" for j in joins) + " |",
            "|---|" + "---|" * len(joins),
        ]
        for m in METRICS:
            cells = [
                cell([r[m] for r in rows if r["scenario"] == scenario and r["join"] == j])
                for j in joins
            ]
            lines.append(f"| {m.replace('_', ' ')} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--seeds", type=int, default=5)
    parser.add_argument("--join", type=int, default=1000, help="the late joiner's first day")
    args = parser.parse_args()
    joins = (0, args.join)
    rows = [
        run(scenario, seed, join)
        for scenario in SCENARIOS
        for seed in range(1, args.seeds + 1)
        for join in joins
    ]
    RESULTS.mkdir(exist_ok=True)
    with (RESULTS / "late_joiners.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    report = summarise(rows, joins)
    (RESULTS / "late_joiners.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
